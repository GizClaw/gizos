void h2_alipay_amount_bitmap(const char* text, char bitmap[32][14]) {
  size_t length = strlen(text);
  if (length > 7u) return;
  size_t column = (7u - length) / 2u;
  bool after_dot = false;
  for (size_t index = 0u; index < length; ++index, ++column) {
    if (text[index] == '.') {
      for (size_t row = 0u; row < 32u; ++row)
        bitmap[row][column * 2u] = row >= 25u && row <= 27u ? 0x60 : 0;
      after_dot = true;
    } else if (text[index] >= '0' && text[index] <= '9') {
      size_t offset = column * 2u - (after_dot ? 1u : 0u);
      for (size_t row = 0u; row < 32u; ++row) {
        uint16_t bits = digits[(unsigned)(text[index] - '0')][row];
        bitmap[row][offset] = (char)(bits >> 8u);
        bitmap[row][offset + 1u] = (char)(bits & 0xffu);
      }
    } else {
      return;
    }
  }
}
