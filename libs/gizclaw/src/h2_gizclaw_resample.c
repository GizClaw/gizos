bool h2_gizclaw_resample_reset(h2_gizclaw_resample_t *r, uint32_t rate,
                               uint32_t phase) {
  if (r == NULL || rate < H2_GIZCLAW_RESAMPLE_RATE_MIN ||
      rate > H2_GIZCLAW_RESAMPLE_RATE_MAX || phase >= rate)
    return false;
  const uint32_t out = H2_GIZCLAW_RESAMPLE_OUTPUT_RATE;
  r->rate = rate;
  if (rate == out) {
    r->half = 0;
    r->step = 0.0f;
    r->whole = r->len = 0;
    r->num = 0;
    return phase == 0;
  }
  /* Decimation widens the window by the rate ratio so the cutoff stays at
   * 7 kHz; interpolation cuts at 7/8 of the source Nyquist. */
  r->half = rate > out ? (KERNEL_ZEROS * rate + out - 1u) / out : KERNEL_ZEROS;
  r->step = rate > out ? (float)KERNEL_STEPS * (float)out / (float)rate
                       : (float)KERNEL_STEPS;
  memset(r->buf, 0, r->half * sizeof(r->buf[0]));
  r->len = r->half;
  r->whole = r->half + phase / out;
  r->num = phase % out;
  return true;
}

size_t h2_gizclaw_resample_capacity(const h2_gizclaw_resample_t *r,
                                    size_t count) {
  if (r->rate == H2_GIZCLAW_RESAMPLE_OUTPUT_RATE)
    return count;
  return (count + r->half) * H2_GIZCLAW_RESAMPLE_OUTPUT_RATE / r->rate + 2u;
}

/* One output at the current position, normalised by the weights it used so
 * every phase has unity gain at DC. */
static int16_t output_at(const h2_gizclaw_resample_t *r) {
  const float limit = (float)(KERNEL_ZEROS * KERNEL_STEPS);
  const float frac = (float)r->num / (float)H2_GIZCLAW_RESAMPLE_OUTPUT_RATE;
  const float *x = r->buf + r->whole;
  const int32_t half = (int32_t)r->half;
  float acc = 0.0f, sum = 0.0f;
  for (int32_t j = 1 - half; j <= half; ++j) {
    const float d = frac - (float)j;
    const float u = (d < 0.0f ? -d : d) * r->step;
    if (u >= limit)
      continue;
    const uint32_t i = (uint32_t)u;
    const float w = kernel[i] + (u - (float)i) * (kernel[i + 1u] - kernel[i]);
    acc += w * x[j];
    sum += w;
  }
  float y = sum > 0.0f ? acc / sum : 0.0f;
  if (y >= 32767.0f)
    return 32767;
  if (y <= -32768.0f)
    return -32768;
  return (int16_t)(y < 0.0f ? y - 0.5f : y + 0.5f);
}

static void advance(h2_gizclaw_resample_t *r) {
  r->num += r->rate;
  r->whole += r->num / H2_GIZCLAW_RESAMPLE_OUTPUT_RATE;
  r->num %= H2_GIZCLAW_RESAMPLE_OUTPUT_RATE;
}

size_t h2_gizclaw_resample_push(h2_gizclaw_resample_t *r, const int16_t *in,
                                size_t count, int16_t *out) {
  if (r->rate == H2_GIZCLAW_RESAMPLE_OUTPUT_RATE) {
    memcpy(out, in, count * sizeof(in[0]));
    return count;
  }
  for (size_t i = 0; i < count; ++i)
    r->buf[r->len + i] = (float)in[i];
  r->len += count;
  size_t produced = 0;
  while (r->whole + r->half < r->len) {
    out[produced++] = output_at(r);
    advance(r);
  }
  /* Keep only what the next output's window reaches back to. */
  size_t drop = r->whole + 1u - r->half;
  if (drop > r->len)
    drop = r->len;
  memmove(r->buf, r->buf + drop, (r->len - drop) * sizeof(r->buf[0]));
  r->len -= drop;
  r->whole -= drop;
  return produced;
}

size_t h2_gizclaw_resample_flush(h2_gizclaw_resample_t *r, int16_t *out) {
  if (r->rate == H2_GIZCLAW_RESAMPLE_OUTPUT_RATE)
    return 0;
  const size_t end = r->len;
  memset(r->buf + r->len, 0, r->half * sizeof(r->buf[0]));
  r->len += r->half;
  size_t produced = 0;
  while (r->whole < end) {
    out[produced++] = output_at(r);
    advance(r);
  }
  r->len = end;
  return produced;
}
