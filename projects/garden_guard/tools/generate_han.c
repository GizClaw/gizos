/* Regenerates the checked-in bitmap from the shared OFL Noto Sans SC font.
 * Usage: generate_han FONT UTF8_CATALOG_SOURCE > h2_garden_guard_zh.inc */
#include <ft2build.h>
#include FT_FREETYPE_H

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define HAN_SIDE 16
#define BMP_COUNT 65536u

int main(int argc, char** argv) {
  if (argc != 3) return 2;
  FILE* input = fopen(argv[2], "rb");
  if (input == NULL) return 2;
  static bool used[BMP_COUNT];
  int byte;
  while ((byte = fgetc(input)) != EOF) {
    if (byte < 128) continue;
    const int second = fgetc(input);
    const int third = fgetc(input);
    if (byte < 0xe0 || byte > 0xef || second < 0x80 || second > 0xbf ||
        third < 0x80 || third > 0xbf) {
      fclose(input);
      fprintf(stderr, "Expected three-byte UTF-8 catalog characters\n");
      return 2;
    }
    used[((unsigned)byte & 15u) << 12 | ((unsigned)second & 63u) << 6 |
         ((unsigned)third & 63u)] = true;
  }
  fclose(input);
  FT_Library library;
  FT_Face face;
  if (FT_Init_FreeType(&library) || FT_New_Face(library, argv[1], 0, &face) ||
      FT_Set_Pixel_Sizes(face, 0, HAN_SIDE))
    return 2;

  puts(
      "/* Generated by tools/generate_han.c. Source: Noto Sans SC Bold.\n"
      " * SIL OFL 1.1, see tools/noto_sans_sc_bitmap_license.txt. */\n"
      "#define HAN_SIDE 16\n"
      "static const struct {\n"
      "  uint16_t code;\n"
      "  uint32_t rows[HAN_SIDE];\n"
      "} k_han[] = {");

  for (unsigned code = 128u; code < BMP_COUNT; ++code) {
    if (!used[code]) continue;
    if (FT_Get_Char_Index(face, code) == 0 ||
        FT_Load_Char(face, code, FT_LOAD_RENDER | FT_LOAD_NO_HINTING)) {
      fprintf(stderr, "Font is missing U+%04X\n", code);
      return 1;
    }
    const FT_Bitmap* bitmap = &face->glyph->bitmap;
    if (bitmap->width > HAN_SIDE || bitmap->rows > HAN_SIDE ||
        bitmap->pixel_mode != FT_PIXEL_MODE_GRAY || bitmap->pitch < 0)
      return 1;
    uint32_t rows[HAN_SIDE] = {0};
    /* Align every ideograph and punctuation mark to the same baseline. */
    int top = 14 - face->glyph->bitmap_top;
    if (top < 0) top = 0;
    if (top + (int)bitmap->rows > HAN_SIDE) top = HAN_SIDE - (int)bitmap->rows;
    int left = face->glyph->bitmap_left;
    if (left < 0) left = 0;
    if (left + (int)bitmap->width > HAN_SIDE)
      left = HAN_SIDE - (int)bitmap->width;
    for (unsigned y = 0; y < bitmap->rows; ++y)
      for (unsigned x = 0; x < bitmap->width; ++x) {
        const unsigned alpha = bitmap->buffer[y * (unsigned)bitmap->pitch + x];
        rows[(unsigned)top + y] |= ((alpha * 3u + 127u) / 255u)
                                   << (2u * ((unsigned)left + x));
      }
    printf("    {0x%04xu, {", code);
    for (unsigned y = 0; y < HAN_SIDE; ++y) {
      if (y != 0) fputs(y % 5u == 0 ? ",\n               " : ", ", stdout);
      printf("0x%08lxu", (unsigned long)rows[y]);
    }
    puts("}},");
  }
  puts("};");
  FT_Done_Face(face);
  FT_Done_FreeType(library);
  return ferror(stdout) ? EXIT_FAILURE : EXIT_SUCCESS;
}
