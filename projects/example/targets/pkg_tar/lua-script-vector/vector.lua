local display = require('display')
local delay = require('delay')

display.clear('black')
display.fill_polygon({{10,10},{60,10},{60,40},{10,40}}, 'red')
display.fill_ellipse(100,100,20,10,'blue',0,90,110)

local source = {{0,10,10,10,10,'red'}, {1,-100000,40,100000,40,'blue'}}
local commands = display.compile_commands(source)
source[1][2] = 1000
source = nil
collectgarbage('collect')
display.draw_commands(commands,150,181,0,140,2,1,{r=0,g=255,b=0})
assert(not pcall(display.draw_commands,commands,0,240,0,0,0))
assert(not pcall(display.fill_polygon,{{0,0},{10,0},{0/0,10}},'white'))
assert(not pcall(display.fill_ellipse,10,10,1,0,'white'))
display.draw_commands(display.compile_commands({}))
local native = require('vector_native')
local mesh = native.new()
display.draw_mesh(mesh,{cache=true})
display.draw_mesh(mesh,{cache=true})
-- Empty clipping still prepares a different transform; identity must replace it.
display.draw_mesh(mesh,{matrix={-1,0,0,1,200,0},left=0,right=0,cache=true})
display.draw_mesh(mesh,{matrix={1,0,0,1,0,0},grid=0,cache=true})
-- A coordinate-cache hit without span replay must still read owned vertices.
display.draw_mesh(mesh)
native.move(mesh,10,40)
assert(not pcall(native.move,mesh,math.huge,0))
collectgarbage('collect')
display.draw_mesh(mesh,{left=160,right=190,top=60,bottom=90,cache=true})
mesh = nil
collectgarbage('collect')
local points, widths = {{20.5,210.5},{60.5,210.5}}, {3}
assert(not display.stroke_path(points,widths,'red',0,0,display.height,true,true))
assert(display.stroke_path(points,widths,'red',0,0,display.height,true,true))
display.stroke_path({{90.5,210.5},{130.5,210.5}},{1},'blue',0,0,display.height,false,false,true)
points, widths = nil, nil
collectgarbage('collect')
local background = display.capture_region(0,0,display.width,display.height)
display.restore_background(background)
local submitted, rectangles = display.present({retained=true})
assert(submitted==display.width*display.height and rectangles==1)
display.fill_rect(200,200,8,8,'red')
display.restore_background(background)
assert(display.present()==0)
local region = display.capture_region(5,5,16,16,'black')
display.draw_region(region,210,210,0,display.height,'black')
submitted, rectangles = display.present()
assert(submitted==1024 and rectangles==1)
assert(display.present()==0)
display.release_background()
background, region = nil, nil
collectgarbage('collect')
-- Prepared built-ins run through the same Host, without native registration.
local v,g=require('vmath'),require('geometry')
local function b(t) local out=v.buffer(#t);out:load(t);return out end
local w=v.constraints(2,1)
w:load(b{0,0,0,1.000000001,0,0},b{0,0,0,1,0,0},b{1,2,1,.0001,0,1},2,1,.01)
w:begin(.01);w:solve(3,nil,0)
local p,prev,lambda=v.buffer(6),v.buffer(6),v.buffer(1)
w:copy(p,prev,lambda);assert(lambda:get(1)<0)
w:bind(p,prev,b{1,2,1,.0001,0,1},2,1,.01)
p:set(4,2);assert(w:node(2)==2)
w:solve(1,nil,0);assert(w:multipliers(1)<0 and p:get(4)<2)
w:load(p,prev,b{1,2,1,.0001,0,1},2,1,.01)
-- Explicit source arithmetic is available in the real Web source package.
local delta=v.buffer(6,'f32');w:node(2,999999.001,0,0,999999,0,0)
w:displacements(delta,2,1);assert(math.abs(delta:get(1)-.001)<1e-9)
local zero,one=v.buffer(3,'f32'),v.buffer(3,'f32');one:fill(1)
w:integrate(2,1,b{1},zero,one,b{1,1,1},b{0,0,0},'displacement-f32',nil,0)
assert(w:node(2)>999999.001)
local norm=v.buffer(1);v.length3_refined(norm,b{.3,.4,0},1)
assert(math.abs(norm:get(1)-.5)<1e-12)
local rotations=g.rotations(b{.25,0,0},b{1},b{0,0,1},1)
local endpoint=v.buffer(3)
assert(rotations:evaluate(endpoint,0,1.6,0,0,0,0,false,false))
assert(math.abs(endpoint:get(1)-.25*math.cos(1.6))<1e-9)
assert(not rotations:evaluate(endpoint,0,2,0,0,0,0,false,false))
local pose=g.pose(g.batch(b{0,0,8,0,8,8,0,8},b{0,1,4},nil,nil,b{0,0,0,0},4,1))
assert(not pose:evaluate(0,0,10,230,1,0,1,nil))
assert(pose:evaluate(0,0,10,230,1,0,1,nil))
display.draw_pose(pose,b{0xf800},0,0,0,0,1,0,0,0,240,240)
local chain=display.polyline(2);chain:load(b{-2,0,1,2,0,1},2)
local blue=display.compile_line_style(b{0x001f})
local green=display.compile_line_style(b{0x07e0})
local white=display.compile_line_style(b{0xffff})
display.draw_polyline(chain,b{40,234,2,0,1},1,0,false,green,blue,white,0,0,240,240)
local stroke={buffer=b{180,230,190,230},count=2};local widths={1}
display.stroke_path(stroke,widths,'white',0,0,240,true,true)
assert(display.stroke_path(stroke,widths,'white',0,0,240,true,true))
local transformed=display.compile_mesh({{0,0},{8,0},{8,8},{0,8}},{{0,1,4,'blue'}})
local mesh_opts={transform={x=200.01,y=120,scale=1,angle=0},grid=2,cache=true}
display.draw_mesh(transformed,mesh_opts)
display.update_mesh(transformed,{{.01,0},{8,0},{8,8},{0,8}},{{0,1,4,'blue'}})
display.draw_mesh(transformed,mesh_opts)
display.present()
print('LUA_VECTOR calls=PASS')
while true do delay.delay_ms(20) end
